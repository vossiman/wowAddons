-- Shuffled deck: no headline repeats until every one has run.
local deck = {}
local function draw()
    if #deck == 0 then
        for i = 1, #HEADLINES do deck[i] = i end
        for i = #deck, 2, -1 do
            local j = math.random(i)
            deck[i], deck[j] = deck[j], deck[i]
        end
    end
    return HEADLINES[table.remove(deck)]
end

local lastMob = "BOAR"
GTA:OnKill(function(name) lastMob = name:upper() end)

local jumps = 0
if type(JumpOrAscendStart) == "function" then hooksecurefunc("JumpOrAscendStart", function() jumps = jumps + 1 end) end

local function rideName()
    if C_MountJournal and C_MountJournal.GetMountIDs then
        for _, id in ipairs(C_MountJournal.GetMountIDs()) do
            local ok, name, _, _, isActive = pcall(C_MountJournal.GetMountInfoByID, id)
            if ok and isActive then return Safe(name) end
        end
    end
    return "STOLEN KODO"
end

local function fill(text)
    local s = GTA.db.stats
    local ok, speed = pcall(GetUnitSpeed, "player")
    local values = {
        NAME = (UnitName("player") or "SOMEONE"):upper(),
        CLASS = (UnitClass("player") or "ADVENTURER"):upper(),
        RACE = (UnitRace("player") or "STRANGER"):upper(),
        LEVEL = tostring(UnitLevel("player") or "??"),
        ZONE = (Safe(GetZoneText()) or "AZEROTH"):upper(),
        SUB = ((Safe(GetSubZoneText()) ~= "" and Safe(GetSubZoneText())) or Safe(GetZoneText()) or "TOWN"):upper(),
        MOB = lastMob,
        DEATHS = tostring(s.deaths or 0),
        MISSIONS = tostring(s.missions or 0),
        KILLS = tostring(math.max(3, s.kills or 0)),
        RIDES = tostring(s.rides or 0),
        CASH = GTA.Commas(GetMoney()),
        RANK = (GTA.Rank and GTA:Rank() or "STREET RAT"):upper(),
        STARS = tostring(math.max(1, GTA:Wanted())),
        JUMPS = tostring(math.max(12, jumps)),
        SPEED = tostring(math.max(90, math.floor((ok and Safe(speed) or 9) * 10))),
        RIDE = "",
    }
    if text:find("{RIDE}") then values.RIDE = (rideName() or "STOLEN KODO"):upper() end
    return (text:gsub("{(%u+)}", function(k) return values[k] or k end))
end

function GTA:BreakingNews()
    self:News(fill(draw()))
end
